#!/usr/bin/env python3
"""Render and verify repository agent instructions."""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
import tempfile
from pathlib import Path
from typing import Any


ROOT = Path(__file__).resolve().parents[2]
PM_DIR = Path(__file__).resolve().parent
CONFIG_PATH = PM_DIR / "targets.json"
RATCHET_PATH = PM_DIR / "context-size-ratchet.json"


class PromptManagerError(RuntimeError):
    """Configuration, rendering, or validation failure."""


def load_json(path: Path) -> dict[str, Any]:
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise PromptManagerError(f"cannot read {path.relative_to(ROOT)}: {exc}") from exc
    if not isinstance(value, dict):
        raise PromptManagerError(f"{path.relative_to(ROOT)} must contain a JSON object")
    return value


def load_config() -> dict[str, Any]:
    config = load_json(CONFIG_PATH)
    if not isinstance(config.get("targets"), dict) or not config["targets"]:
        raise PromptManagerError("targets.json must define non-empty targets")
    if not isinstance(config.get("context_groups"), dict):
        raise PromptManagerError("targets.json must define context_groups")
    if not isinstance(config.get("retired_outputs"), list):
        raise PromptManagerError("targets.json must define retired_outputs")
    return config


def read_source(relative: str) -> str:
    path = (PM_DIR / relative).resolve()
    if PM_DIR not in path.parents or path.parent == PM_DIR:
        raise PromptManagerError(f"source must stay under tools/prompt-manager/: {relative}")
    try:
        return path.read_text(encoding="utf-8").rstrip() + "\n"
    except OSError as exc:
        raise PromptManagerError(f"cannot read source {relative}: {exc}") from exc


def render_target(spec: dict[str, Any]) -> str:
    body = read_source(require_string(spec, "source"))
    kind = require_string(spec, "kind")
    if kind == "plain":
        return body
    if kind == "cursor_rule":
        description = require_string(spec, "description")
        globs = require_string(spec, "globs")
        return (
            "---\n"
            f"description: {json.dumps(description)}\n"
            f"globs: {json.dumps(globs)}\n"
            "alwaysApply: false\n"
            "---\n"
            "<!-- Generated by tools/prompt-manager/pm.py. Edit sources, not this file. -->\n"
            f"{body}"
        )
    if kind == "claude_rule":
        paths = spec.get("paths")
        if not isinstance(paths, list) or not paths or not all(
            isinstance(path, str) and path for path in paths
        ):
            raise PromptManagerError("claude_rule requires a non-empty string paths list")
        lines = ["---", "paths:"]
        lines.extend(f"  - {json.dumps(path)}" for path in paths)
        lines.extend(
            [
                "---",
                "<!-- Generated by tools/prompt-manager/pm.py. Edit sources, not this file. -->",
                body.rstrip(),
                "",
            ]
        )
        return "\n".join(lines)
    raise PromptManagerError(f"unsupported target kind: {kind}")


def require_string(mapping: dict[str, Any], key: str) -> str:
    value = mapping.get(key)
    if not isinstance(value, str) or not value:
        raise PromptManagerError(f"target field {key!r} must be a non-empty string")
    return value


def output_path(spec: dict[str, Any]) -> Path:
    relative = Path(require_string(spec, "output"))
    path = (ROOT / relative).resolve()
    if path != ROOT and ROOT not in path.parents:
        raise PromptManagerError(f"output escapes repository: {relative}")
    return path


def measure(content: str) -> dict[str, int]:
    return {
        "bytes": len(content.encode("utf-8")),
        "lines": len(content.splitlines()),
    }


def render_all(config: dict[str, Any]) -> dict[str, str]:
    rendered: dict[str, str] = {}
    outputs: set[Path] = set()
    for name, raw_spec in config["targets"].items():
        if not isinstance(name, str) or not isinstance(raw_spec, dict):
            raise PromptManagerError("target names must map to objects")
        path = output_path(raw_spec)
        if path in outputs:
            raise PromptManagerError(f"duplicate output path: {path.relative_to(ROOT)}")
        outputs.add(path)
        rendered[name] = render_target(raw_spec)
    return rendered


def current_sizes(
    config: dict[str, Any], rendered: dict[str, str]
) -> dict[str, dict[str, dict[str, int]]]:
    targets = {name: measure(content) for name, content in rendered.items()}
    groups: dict[str, dict[str, int]] = {}
    for group_name, raw_group in config["context_groups"].items():
        if not isinstance(raw_group, dict) or not isinstance(raw_group.get("targets"), list):
            raise PromptManagerError(f"invalid context group: {group_name}")
        members = raw_group["targets"]
        unknown = [name for name in members if name not in targets]
        if unknown:
            raise PromptManagerError(f"context group {group_name} has unknown targets: {unknown}")
        groups[group_name] = {
            "bytes": sum(targets[name]["bytes"] for name in members),
            "lines": sum(targets[name]["lines"] for name in members),
        }
    return {"groups": groups, "targets": targets}


def validate_budgets(
    config: dict[str, Any], sizes: dict[str, dict[str, dict[str, int]]]
) -> None:
    for name, spec in config["targets"].items():
        validate_one_budget(f"target {name}", spec, sizes["targets"][name])
    for name, spec in config["context_groups"].items():
        validate_one_budget(f"context group {name}", spec, sizes["groups"][name])


def validate_one_budget(label: str, spec: dict[str, Any], size: dict[str, int]) -> None:
    for dimension, key in (("bytes", "max_bytes"), ("lines", "max_lines")):
        ceiling = spec.get(key)
        if not isinstance(ceiling, int) or ceiling <= 0:
            raise PromptManagerError(f"{label} requires positive {key}")
        if size[dimension] > ceiling:
            raise PromptManagerError(
                f"{label} exceeds {key}: {size[dimension]} > {ceiling}"
            )


def validate_scoping(config: dict[str, Any], rendered: dict[str, str]) -> None:
    for name, spec in config["targets"].items():
        kind = spec["kind"]
        output = spec["output"]
        content = rendered[name]
        if kind == "cursor_rule":
            if not output.endswith(".mdc") or not output.startswith(".cursor/rules/"):
                raise PromptManagerError(f"Cursor target {name} must be .cursor/rules/*.mdc")
            if "\nalwaysApply: false\n" not in content or "\nglobs: " not in content:
                raise PromptManagerError(f"Cursor target {name} must be file-scoped")
            patterns = [pattern.strip() for pattern in spec["globs"].split(",")]
            validate_scope_paths(name, patterns)
        elif kind == "claude_rule":
            if not output.endswith(".md") or not output.startswith(".claude/rules/"):
                raise PromptManagerError(f"Claude target {name} must be .claude/rules/*.md")
            if not content.startswith("---\npaths:\n"):
                raise PromptManagerError(f"Claude target {name} must use paths frontmatter")
            validate_scope_paths(name, spec["paths"])


def validate_scope_paths(name: str, patterns: list[str]) -> None:
    for pattern in patterns:
        relative = Path(pattern)
        if not pattern or relative.is_absolute() or ".." in relative.parts:
            raise PromptManagerError(f"invalid scope path in {name}: {pattern!r}")
        if any(character in pattern for character in "*?[]{}"):
            continue
        # exists() accepts wrong casing on common macOS filesystems. Compare
        # directory entries explicitly so literal scopes also work on Linux.
        candidate = ROOT
        for part in relative.parts:
            if not candidate.is_dir() or part not in {entry.name for entry in candidate.iterdir()}:
                raise PromptManagerError(f"missing or wrong-case scope path in {name}: {pattern}")
            candidate = candidate / part
        if not candidate.is_file():
            raise PromptManagerError(f"literal scope must name a file in {name}: {pattern}")


def imports(content: str) -> list[str]:
    prose: list[str] = []
    fence = ""
    for line in content.splitlines(keepends=True):
        marker = re.match(r"^ {0,3}(`{3,}|~{3,})(.*)$", line.rstrip("\n"))
        if fence:
            if (marker and marker[1][0] == fence[0]
                    and len(marker[1]) >= len(fence) and not marker[2].strip()):
                fence = ""
        elif marker:
            fence = marker[1]
        else:
            prose.append(line)
    without_code = re.sub(r"(`+)(?!`).*?(?<!`)\1(?!`)", "", "".join(prose), flags=re.S)
    return re.findall(r"(?<![\w@])@([A-Za-z0-9_./~-]+)", without_code)


def validate_imports(config: dict[str, Any], rendered: dict[str, str]) -> None:
    available = {output_path(spec): name for name, spec in config["targets"].items()}
    edges: dict[str, list[str]] = {}
    for name, content in rendered.items():
        edges[name] = []
        for raw_import in imports(content):
            imported = Path(raw_import)
            if imported.is_absolute() or str(imported).startswith("~"):
                raise PromptManagerError(f"external import is not allowed in {name}: @{imported}")
            candidate = (output_path(config["targets"][name]).parent / imported).resolve()
            if candidate != ROOT and ROOT not in candidate.parents:
                raise PromptManagerError(f"external import is not allowed in {name}: @{imported}")
            if candidate not in available and not candidate.is_file():
                raise PromptManagerError(f"missing import in {name}: @{imported}")
            if candidate not in available:
                raise PromptManagerError(f"unbudgeted import in {name}: @{imported}; use an on-demand route")
            edges[name].append(available[candidate])
    groups = config.get("context_groups", {})
    for name, imported_targets in edges.items():
        if imported_targets and not any(name in group["targets"] for group in groups.values()):
            raise PromptManagerError(f"import without context group in {name}")
    for group_name, group in groups.items():
        members = set(group["targets"])
        for name in members:
            if any(imported not in members for imported in edges[name]):
                raise PromptManagerError(f"import escapes context group {group_name}: {name}")

    def visit(name: str, active: set[str], visited: set[str]) -> None:
        if name in active:
            raise PromptManagerError(f"import cycle at {name}")
        if name in visited:
            return
        for imported in edges[name]:
            visit(imported, active | {name}, visited)
        visited.add(name)

    visited: set[str] = set()
    for name in edges:
        visit(name, set(), visited)
    for name, spec in config["targets"].items():
        if "required_imports" not in spec:
            continue
        required = spec["required_imports"]
        if (not isinstance(required, list)
                or not all(isinstance(target, str) and target in available.values() for target in required)
                or len(required) != len(set(required))):
            raise PromptManagerError(f"invalid required_imports in {name}")
        if edges[name] != required:
            raise PromptManagerError(f"import contract changed in {name}: expected {required}, got {edges[name]}")


def validate_retired(config: dict[str, Any]) -> None:
    for raw_path in config["retired_outputs"]:
        if not isinstance(raw_path, str) or not raw_path:
            raise PromptManagerError("retired_outputs entries must be non-empty strings")
        if (ROOT / raw_path).exists():
            raise PromptManagerError(f"retired prompt file exists: {raw_path}")


def validate_managed_rule_directories(config: dict[str, Any]) -> None:
    expected = {
        output_path(spec)
        for spec in config["targets"].values()
        if spec["kind"] in {"cursor_rule", "claude_rule"}
    }
    for relative in (Path(".cursor/rules"), Path(".claude/rules")):
        directory = ROOT / relative
        if not directory.exists():
            continue
        unmanaged = sorted(
            path.relative_to(ROOT)
            for path in directory.rglob("*")
            if path.is_file() and path.resolve() not in expected
        )
        if unmanaged:
            joined = ", ".join(str(path) for path in unmanaged)
            raise PromptManagerError(f"unmanaged scoped prompt file(s): {joined}")


def ratchet_identities(config: dict[str, Any]) -> dict[str, Any]:
    return {
        "outputs": {name: spec["output"] for name, spec in config["targets"].items()},
        "group_members": {
            name: spec["targets"] for name, spec in config["context_groups"].items()
        },
    }


def validate_ratchet(config: dict[str, Any], sizes: dict[str, dict[str, dict[str, int]]]) -> None:
    if not RATCHET_PATH.is_file():
        raise PromptManagerError("missing context-size-ratchet.json; initialize it with ratchet --update")
    ratchet = load_json(RATCHET_PATH)
    for identity, expected in ratchet_identities(config).items():
        if ratchet.get(identity) != expected:
            raise PromptManagerError(
                f"ratchet {identity} changed; review targets.json and edit the baseline explicitly"
            )
    for section in ("targets", "groups"):
        expected = sizes[section]
        recorded = ratchet.get(section)
        if not isinstance(recorded, dict) or set(recorded) != set(expected):
            raise PromptManagerError(
                f"ratchet {section} identities changed; review targets.json and update the baseline explicitly"
            )
        for name, size in expected.items():
            ceiling = recorded.get(name)
            if not isinstance(ceiling, dict):
                raise PromptManagerError(f"invalid ratchet entry: {section}.{name}")
            for dimension in ("bytes", "lines"):
                value = ceiling.get(dimension)
                if not isinstance(value, int) or size[dimension] > value:
                    raise PromptManagerError(
                        f"ratchet growth: {section}.{name}.{dimension} "
                        f"{size[dimension]} > {value}"
                    )


def validate_all(
    config: dict[str, Any], rendered: dict[str, str], *, ratchet: bool = True
) -> dict[str, dict[str, dict[str, int]]]:
    sizes = current_sizes(config, rendered)
    validate_budgets(config, sizes)
    validate_scoping(config, rendered)
    validate_imports(config, rendered)
    validate_retired(config)
    validate_managed_rule_directories(config)
    if ratchet:
        validate_ratchet(config, sizes)
    return sizes


def atomic_write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
            handle.write(content)
        os.replace(temporary, path)
    except BaseException:
        try:
            os.unlink(temporary)
        except FileNotFoundError:
            pass
        raise


def command_sync(config: dict[str, Any], *, dry_run: bool) -> None:
    rendered = render_all(config)
    validate_all(config, rendered)
    changed: list[str] = []
    for name, content in rendered.items():
        path = output_path(config["targets"][name])
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current != content:
            changed.append(str(path.relative_to(ROOT)))
            if not dry_run:
                atomic_write(path, content)
    mode = "would update" if dry_run else "updated"
    print(f"prompt-manager sync: {mode} {len(changed)} file(s)")
    for path in changed:
        print(f"- {path}")


def command_check(config: dict[str, Any]) -> None:
    rendered = render_all(config)
    sizes = validate_all(config, rendered)
    drift: list[str] = []
    for name, content in rendered.items():
        path = output_path(config["targets"][name])
        if not path.is_file() or path.read_text(encoding="utf-8") != content:
            drift.append(str(path.relative_to(ROOT)))
    if drift:
        raise PromptManagerError(
            "generated prompt drift; run just pm-sync: " + ", ".join(drift)
        )
    print(
        "prompt-manager check: ok "
        f"({len(rendered)} targets, {len(sizes['groups'])} startup groups)"
    )


def command_status(config: dict[str, Any]) -> None:
    rendered = render_all(config)
    sizes = validate_all(config, rendered)
    for name, spec in config["targets"].items():
        size = sizes["targets"][name]
        print(
            f"target {name}: {spec['kind']} {spec['output']} "
            f"{size['bytes']} bytes/{size['lines']} lines"
        )
    for name, size in sizes["groups"].items():
        print(f"group {name}: {size['bytes']} bytes/{size['lines']} lines")


def command_ratchet_update(config: dict[str, Any]) -> None:
    rendered = render_all(config)
    sizes = validate_all(config, rendered, ratchet=False)
    if RATCHET_PATH.is_file():
        current = load_json(RATCHET_PATH)
        for identity, expected in ratchet_identities(config).items():
            if current.get(identity) != expected:
                raise PromptManagerError(
                    f"ratchet {identity} changed; edit the baseline in the same reviewed change"
                )
        for section in ("targets", "groups"):
            old_section = current.get(section)
            if not isinstance(old_section, dict) or set(old_section) != set(sizes[section]):
                raise PromptManagerError(
                    f"ratchet {section} identities changed; edit the baseline in the same reviewed change"
                )
            for name, size in sizes[section].items():
                for dimension in ("bytes", "lines"):
                    old = old_section[name][dimension]
                    if size[dimension] > old:
                        raise PromptManagerError(
                            f"ratchet update cannot raise {section}.{name}.{dimension}: "
                            f"{size[dimension]} > {old}"
                        )
    atomic_write(RATCHET_PATH, json.dumps({**sizes, **ratchet_identities(config)}, indent=2, sort_keys=True) + "\n")
    print("prompt-manager ratchet: updated shrink-only ceilings")


def parse_args(argv: list[str]) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    subparsers = parser.add_subparsers(dest="command", required=True)
    sync = subparsers.add_parser("sync", help="render generated instruction files")
    sync.add_argument("--dry-run", action="store_true")
    subparsers.add_parser("check", help="validate outputs, scopes, and budgets")
    subparsers.add_parser("status", help="show target and startup context sizes")
    ratchet = subparsers.add_parser("ratchet", help="manage shrink-only size ceilings")
    ratchet.add_argument("--update", action="store_true", required=True)
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(sys.argv[1:] if argv is None else argv)
    try:
        config = load_config()
        if args.command == "sync":
            command_sync(config, dry_run=args.dry_run)
        elif args.command == "check":
            command_check(config)
        elif args.command == "status":
            command_status(config)
        elif args.command == "ratchet":
            command_ratchet_update(config)
        else:
            raise PromptManagerError(f"unsupported command: {args.command}")
    except PromptManagerError as exc:
        print(f"prompt-manager: error: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
