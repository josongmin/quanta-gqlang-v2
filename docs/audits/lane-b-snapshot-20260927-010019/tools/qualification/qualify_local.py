#!/usr/bin/env python3
"""Qualify one clean HEAD in a persistent, isolated local worktree.

The checkout path stays fixed across source pins. Rust tests can embed
CARGO_MANIFEST_DIR at compile time, so sharing a target directory between
different checkout paths can reuse an invalid test binary. Only this driver
uses its managed worktree and build cache; Cargo chooses which artifacts to
rebuild after a source or toolchain change.
"""

from __future__ import annotations

import fcntl
import hashlib
import json
import os
import re
import stat
import subprocess
import sys
import tempfile
import time
import uuid
from pathlib import Path
from typing import Optional, Sequence

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from tools.process_guard import ProcessTimeoutError, run_bounded  # noqa: E402
from tools.ci.evidence import (  # noqa: E402
    EvidencePathError, read_bytes_evidence, read_json_evidence,
    write_bytes_evidence, write_json_evidence,
)
from tools.ci.advisory_db import OFFICIAL_ORIGINS, advisory_identity  # noqa: E402
from tools.ci.deny_gate import COMMAND as DENY_COMMAND  # noqa: E402
from tools.ci.run_local import GROUPS as CI_GROUPS  # noqa: E402

GIT_TIMEOUT_S = 120
CI_TIMEOUT_S = 1800
RECIPE_TIME = re.compile(r"^---> ([a-z][a-z0-9-]*) completed in ([0-9.]+)s$", re.MULTILINE)


class QualificationError(RuntimeError):
    """The candidate or managed checkout cannot be qualified safely."""


def command(args: Sequence[str], cwd: Path, *, env: Optional[dict[str, str]] = None) -> str:
    try:
        result = run_bounded(args, cwd=cwd, timeout_s=GIT_TIMEOUT_S, text=True, capture_output=True, env=env)
    except ProcessTimeoutError as error:
        raise QualificationError(str(error)) from error
    if result.returncode != 0:
        detail = (result.stderr or result.stdout or "").strip()
        raise QualificationError(
            "%s failed (exit=%d)%s" % (
                " ".join(args), result.returncode, ": " + detail if detail else ""
            )
        )
    return (result.stdout or "").strip()


def git(root: Path, *args: str) -> str:
    return command(("git", *args), root)


def git_common_dir(root: Path) -> Path:
    value = Path(git(root, "rev-parse", "--git-common-dir"))
    return (root / value).resolve() if not value.is_absolute() else value.resolve()


def source_status(root: Path, *, checkout: bool = False) -> str:
    args = ["status", "--porcelain", "--untracked-files=all"]
    if checkout:
        # The target symlink is generated by this driver, not a source edit.
        args.extend(("--", ".", ":!target"))
    status = git(root, *args)
    # `git status` and `git diff` trust index flags such as assume-unchanged.
    # Check every tracked byte and executable bit against HEAD independently.
    try:
        listing = subprocess.run(
            ("git", "ls-tree", "-rz", "HEAD"), cwd=root, capture_output=True,
            check=True, timeout=GIT_TIMEOUT_S,
        ).stdout
        algorithm = git(root, "rev-parse", "--show-object-format")
        if algorithm not in ("sha1", "sha256"):
            raise QualificationError("unsupported Git object format: " + algorithm)
        changed = []
        for entry in listing.split(b"\0"):
            if not entry:
                continue
            header, raw_path = entry.split(b"\t", 1)
            mode, kind, expected = header.split(b" ")
            if kind != b"blob":
                raise QualificationError("unsupported tracked Git object: " + os.fsdecode(raw_path))
            path = root / os.fsdecode(raw_path)
            try:
                metadata = path.lstat()
                if mode == b"120000":
                    actual = os.fsencode(os.readlink(path)) if stat.S_ISLNK(metadata.st_mode) else None
                elif mode in (b"100644", b"100755") and stat.S_ISREG(metadata.st_mode):
                    actual = path.read_bytes()
                    executable = bool(metadata.st_mode & 0o111)
                    if executable != (mode == b"100755"):
                        actual = None
                else:
                    actual = None
            except (OSError, ValueError):
                actual = None
            if actual is None:
                changed.append(os.fsdecode(raw_path))
                continue
            blob = b"blob " + str(len(actual)).encode("ascii") + b"\0" + actual
            if getattr(hashlib, algorithm)(blob).hexdigest().encode("ascii") != expected:
                changed.append(os.fsdecode(raw_path))
        if changed:
            status += ("\n" if status else "") + "HEAD byte/mode drift: " + ", ".join(changed[:10])
    except (OSError, subprocess.SubprocessError, ValueError) as error:
        raise QualificationError("cannot verify tracked source against HEAD: %s" % error) from error
    return status


def write_json_atomic(path: Path, payload: dict, *, owned_root: Path) -> None:
    try:
        write_json_evidence(
            path, payload, owned_root=owned_root, prefix=path.name.removesuffix(".json")
        )
    except EvidencePathError as error:
        raise QualificationError("cannot write qualification evidence: %s" % error) from error


def source_hashes(checkout: Path) -> dict:
    paths = (
        "Cargo.lock",
        "tools/frontend_external_consumer/Cargo.lock",
        "tools/ci/toolchain.lock.toml",
    )
    return {
        name: hashlib.sha256((checkout / name).read_bytes()).hexdigest()
        for name in paths if (checkout / name).is_file()
    }


def recipe_durations(log_path: Path) -> dict:
    values = {}
    with log_path.open("r", encoding="utf-8", errors="replace") as handle:
        for line in handle:
            match = RECIPE_TIME.match(line)
            if match:
                recipe, seconds = match.groups()
                if recipe in values:
                    raise QualificationError("duplicate Just timing for " + recipe)
                values[recipe] = float(seconds)
    return values


def expected_recipe_names(checkout: Path) -> set:
    if not (checkout / "tools/ci/run_local.py").is_file():
        return {"ci"}
    text = (checkout / "Justfile").read_text(encoding="utf-8")
    expected = {"ci", *CI_GROUPS}
    for group in CI_GROUPS:
        match = re.search(
            r"^" + re.escape(group) + r":\n((?:    [^\n]+\n)+)", text, re.MULTILINE
        )
        if match is None:
            raise QualificationError("cannot identify Just recipe group " + group)
        commands = [line.strip().split() for line in match.group(1).splitlines()]
        expected.update(
            command[1] for command in commands
            if len(command) == 2 and command[0] == "just"
        )
    return expected


def validate_recipe_durations(durations: dict, expected: set) -> None:
    observed = set(durations)
    if observed != expected:
        raise QualificationError(
            "Just timing inventory differs from executed recipes: missing=%s extra=%s"
            % (sorted(expected - observed), sorted(observed - expected))
        )


def hash_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def replay_log(path: Path) -> None:
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            binary = getattr(sys.stdout, "buffer", None)
            if binary is None:
                sys.stdout.write(block.decode("utf-8", errors="replace"))
            else:
                binary.write(block)
    sys.stdout.flush()


def valid_nextest_evidence(evidence: object, run_id: str) -> bool:
    if not isinstance(evidence, dict) or evidence.get("qualification_run_id") != run_id:
        return False
    fields = (
        "discovered", "selected", "executed", "skipped_ignored", "leaked", "exit",
        "summary_run", "summary_passed", "summary_failed", "test_threads",
    )
    if any(type(evidence.get(key)) is not int for key in fields):
        return False
    hashes = (evidence.get("inventory_sha256"), evidence.get("events_sha256"))
    if type(evidence.get("schema")) is not int or evidence["schema"] != 1 or any(
        not isinstance(value, str) or re.fullmatch(r"[0-9a-f]{64}", value) is None
        for value in hashes
    ):
        return False
    if evidence.get("leaked_tests") != [] or evidence.get("unsuccessful") != {}:
        return False
    if evidence["test_threads"] <= 0:
        return False
    return (
        evidence["exit"] == 0 and evidence["selected"] > 0
        and evidence["selected"] == evidence["executed"]
        and evidence["skipped_ignored"] == 0
        and evidence["discovered"] == evidence["executed"] + evidence["skipped_ignored"]
        and evidence["leaked"] == 0
        and evidence["summary_run"] == evidence["selected"]
        and evidence["summary_passed"] == evidence["executed"]
        and evidence["summary_failed"] == 0
    )


def valid_deny_evidence(evidence: object, run_id: str, current: object) -> bool:
    if not isinstance(evidence, dict) or not isinstance(current, dict):
        return False
    if (
        type(evidence.get("schema")) is not int or evidence["schema"] != 1
        or evidence.get("qualification_run_id") != run_id
    ):
        return False
    if (
        type(evidence.get("exit")) is not int
        or evidence["exit"] != 0
        or evidence.get("command") != list(DENY_COMMAND)
    ):
        return False
    output_hash = evidence.get("output_sha256")
    if not isinstance(output_hash, str) or re.fullmatch(r"[0-9a-f]{64}", output_hash) is None:
        return False
    before, after = evidence.get("before"), evidence.get("after")
    if not isinstance(before, dict) or not isinstance(after, dict):
        return False
    identities = [advisory_identity(value) for value in (before, after, current)]
    if identities[0] != identities[1] or identities[1] != identities[2]:
        return False
    path, origin, revision, fetched_at = identities[0]
    return (
        isinstance(path, str) and bool(path)
        and origin in OFFICIAL_ORIGINS
        and isinstance(revision, str) and re.fullmatch(r"[0-9a-f]{40}", revision) is not None
        and type(fetched_at) is int
        and all(type(value.get("fetch_age_s")) is int for value in (before, after, current))
    )


class QualificationDriver:
    def __init__(self, repo_root: Path) -> None:
        self.repo_root = repo_root.resolve()
        self.root = self.repo_root / "target" / "qualification"
        self.checkout = self.root / "managed-checkout"
        self.build_cache = self.root / "managed-build-cache"
        self.marker = self.root / "managed-checkout.json"
        self.lock_path = self.root / ".managed-checkout.lock"

    def ensure_storage_root(self) -> None:
        target_root = self.repo_root / "target"
        if target_root.is_symlink():
            raise QualificationError("repository target root must not be a symlink")
        if target_root.exists() and not target_root.is_dir():
            raise QualificationError("repository target root must be a directory")
        target_root.mkdir(exist_ok=True)
        if self.root.is_symlink():
            raise QualificationError("qualification root must not be a symlink")
        if self.root.exists() and not self.root.is_dir():
            raise QualificationError("qualification root must be a directory")
        self.root.mkdir(exist_ok=True)

    def marker_payload(self) -> dict:
        return {
            "schema": 1,
            "repo_common_dir": str(git_common_dir(self.repo_root)),
            "checkout": str(self.checkout),
            "build_cache": str(self.build_cache),
        }

    def validate_marker(self) -> None:
        if self.marker.is_symlink() or not self.marker.is_file():
            raise QualificationError("managed checkout marker is absent or not a regular file")
        try:
            observed = json.loads(self.marker.read_text(encoding="utf-8"))
        except (OSError, ValueError) as error:
            raise QualificationError("cannot read managed checkout marker: %s" % error) from error
        if observed != self.marker_payload():
            raise QualificationError("managed checkout marker does not match this repository")

    def validate_checkout(self) -> None:
        if self.checkout.is_symlink() or not self.checkout.is_dir():
            raise QualificationError("managed checkout is absent or not a directory")
        if Path(git(self.checkout, "rev-parse", "--show-toplevel")).resolve() != self.checkout:
            raise QualificationError("managed checkout resolves to a different worktree")
        if git_common_dir(self.checkout) != git_common_dir(self.repo_root):
            raise QualificationError("managed checkout belongs to another repository")
        try:
            branch = run_bounded(
                ("git", "symbolic-ref", "--quiet", "HEAD"),
                cwd=self.checkout, timeout_s=GIT_TIMEOUT_S, capture_output=True,
            )
        except ProcessTimeoutError as error:
            raise QualificationError(str(error)) from error
        if branch.returncode == 0:
            raise QualificationError("managed checkout is no longer detached")
        if branch.returncode != 1:
            raise QualificationError("cannot determine managed checkout HEAD mode")
        if self.build_cache.is_symlink() or not self.build_cache.is_dir():
            raise QualificationError("managed build cache is absent or not a directory")
        target = self.checkout / "target"
        if not target.is_symlink() or target.resolve() != self.build_cache:
            raise QualificationError("managed checkout target does not point to its build cache")
        dirty = source_status(self.checkout, checkout=True)
        if dirty:
            raise QualificationError("managed checkout is dirty; inspect before reusing:\n" + dirty)

    def ci_evidence_path(self, name: str) -> Path:
        evidence_dir = self.checkout / "target" / "ci"
        if evidence_dir.is_symlink() or not evidence_dir.is_dir():
            raise QualificationError("managed CI evidence directory is missing or redirected")
        try:
            evidence_dir.resolve().relative_to(self.build_cache.resolve())
        except ValueError as error:
            raise QualificationError("managed CI evidence directory escapes build cache") from error
        path = evidence_dir / name
        if path.is_symlink() or not path.is_file():
            raise QualificationError("managed CI evidence is missing or redirected: " + name)
        return path

    def read_ci_evidence(self, name: str) -> tuple:
        path = self.ci_evidence_path(name)
        try:
            return read_json_evidence(path, owned_root=self.build_cache)
        except (EvidencePathError, OSError) as error:
            raise QualificationError("cannot read managed CI evidence: %s" % error) from error

    def archive_nextest(self, receipt_dir: Path, evidence: dict) -> dict[str, str]:
        archives = {}
        for name, field in (
            ("nextest-list.json", "inventory_sha256"),
            ("nextest-events.jsonl", "events_sha256"),
        ):
            raw = read_bytes_evidence(self.ci_evidence_path(name), owned_root=self.build_cache)
            if hashlib.sha256(raw).hexdigest() != evidence[field]:
                raise QualificationError("Nextest raw stream hash differs from current-run evidence: " + name)
            write_bytes_evidence(receipt_dir / name, raw, owned_root=self.root, prefix=name)
            archives[name] = evidence[field]
        return archives

    def prepare_checkout(self, sha: str, tree: str) -> None:
        if self.checkout.exists() or self.checkout.is_symlink():
            self.validate_marker()
            self.validate_checkout()
            if git(self.checkout, "rev-parse", "HEAD") != sha:
                command(("git", "switch", "--detach", sha), self.checkout)
        else:
            if self.marker.exists() or self.marker.is_symlink():
                raise QualificationError(
                    "managed marker exists without its worktree; inspect Git registration"
                )
            if self.build_cache.exists() or self.build_cache.is_symlink():
                raise QualificationError("unowned managed build-cache path already exists")
            # Claim these exact paths before creating a worktree. A failed add
            # leaves a visible marker and never adopts someone else's data.
            write_json_atomic(self.marker, self.marker_payload(), owned_root=self.root)
            command(
                ("git", "worktree", "add", "--detach", str(self.checkout), sha),
                self.repo_root,
            )
            self.build_cache.mkdir()
            (self.checkout / "target").symlink_to(self.build_cache, target_is_directory=True)
            self.validate_checkout()
        if git(self.checkout, "rev-parse", "HEAD") != sha or \
           git(self.checkout, "rev-parse", "HEAD^{tree}") != tree:
            raise QualificationError("managed checkout did not reach the pinned source/tree")

    def verify_after_run(self, sha: str, tree: str) -> None:
        self.validate_marker()
        self.validate_checkout()
        if git(self.checkout, "rev-parse", "HEAD") != sha or \
           git(self.checkout, "rev-parse", "HEAD^{tree}") != tree:
            raise QualificationError("pinned checkout changed during qualification")
        if git(self.repo_root, "rev-parse", "HEAD") != sha or source_status(self.repo_root):
            raise QualificationError("caller checkout changed during qualification")

    def post_run_dirty(self) -> Optional[bool]:
        try:
            return bool(source_status(self.repo_root)) or bool(
                source_status(self.checkout, checkout=True)
            )
        except (QualificationError, OSError):
            return None

    def run(self) -> int:
        self.ensure_storage_root()
        if self.lock_path.is_symlink():
            raise QualificationError("managed checkout lock must not be a symlink")
        with self.lock_path.open("a+") as lock:
            try:
                fcntl.flock(lock.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
            except BlockingIOError as error:
                raise QualificationError("another local qualification owns the managed checkout") from error
            dirty = source_status(self.repo_root)
            if dirty:
                raise QualificationError("caller checkout is dirty; commit or stash first:\n" + dirty)
            sha = git(self.repo_root, "rev-parse", "HEAD")
            tree = git(self.repo_root, "rev-parse", "HEAD^{tree}")
            print("qualify-local: HEAD sha=" + sha, flush=True)
            print("qualify-local: source tree=" + tree, flush=True)
            self.prepare_checkout(sha, tree)
            print("qualify-local: managed checkout=" + str(self.checkout), flush=True)
            print("qualify-local: managed build cache=" + str(self.build_cache), flush=True)
            print("qualify-local: pinned toolchain:", flush=True)
            print((self.checkout / "rust-toolchain.toml").read_text(encoding="utf-8"),
                  end="", flush=True)
            print("qualify-local: active tool versions:", flush=True)
            observed_tools = {}
            for args in (("rustc", "--version"), ("cargo", "--version"), ("just", "--version")):
                observed_tools[args[0]] = command(args, self.checkout)
                print(observed_tools[args[0]], flush=True)
            if (self.checkout / "tools/ci/doctor.py").is_file():
                try:
                    observed_tools = json.loads(command(
                        ("python3", "-I", "-S", "tools/ci/python_gate.py", "tools/ci/doctor.py", "--json"), self.checkout
                    ))
                except (ValueError, QualificationError) as error:
                    raise QualificationError("tool doctor failed before CI: %s" % error) from error
            hashes = source_hashes(self.checkout)
            run_id = uuid.uuid4().hex
            receipt_dir = self.root / sha
            if receipt_dir.is_symlink():
                raise QualificationError("receipt path must not be a symlink")
            receipt_dir.mkdir(exist_ok=True)
            write_json_atomic(receipt_dir / "receipt.json", {
                "schema": 3, "sha": sha, "tree": tree, "exit": None,
                "status": "running", "dirty": False, "qualification_run_id": run_id,
            }, owned_root=self.root)
            log_path = receipt_dir / "ci.log"
            log_fd, temporary_log = tempfile.mkstemp(dir=str(receipt_dir), prefix=".ci-log-")
            start = time.monotonic()
            try:
                # Keep a per-recipe timing trail even when the caller did not
                # set Just's optional reporting flags. This does not alter
                # which recipes run or the exact-source receipt contract.
                ci_env = {
                    **os.environ, "JUST_TIME": "true", "JUST_TIMESTAMP": "true",
                    "QGLANG_QUALIFICATION_RUN_ID": run_id,
                }
                with os.fdopen(log_fd, "wb") as log_handle:
                    result = run_bounded(
                        ("just", "ci"), cwd=self.checkout, timeout_s=CI_TIMEOUT_S, env=ci_env,
                        output_file=log_handle,
                    )
                exit_code = result.returncode if result.returncode >= 0 else 128 - result.returncode
            except (OSError, ProcessTimeoutError) as error:
                print("qualify-local: " + str(error), file=sys.stderr, flush=True)
                exit_code = 2
            finally:
                os.replace(temporary_log, log_path)
            replay_log(log_path)
            duration_s = int(time.monotonic() - start)
            try:
                self.verify_after_run(sha, tree)
            except QualificationError as error:
                print("qualify-local: " + str(error), file=sys.stderr, flush=True)
                exit_code = 1
            post_run_dirty = self.post_run_dirty()
            if exit_code == 0 and post_run_dirty is not False:
                print("qualify-local: post-run source cleanliness is unavailable or dirty",
                      file=sys.stderr, flush=True)
                exit_code = 2
            nextest_evidence = None
            nextest_raw = None
            if (self.checkout / "tools/ci/nextest_gate.py").is_file():
                try:
                    observed, _ = self.read_ci_evidence("nextest-evidence.json")
                except (OSError, ValueError, QualificationError) as error:
                    print("qualify-local: cannot read nextest evidence: %s" % error,
                          file=sys.stderr, flush=True)
                else:
                    if isinstance(observed, dict) and observed.get("qualification_run_id") == run_id:
                        nextest_evidence = observed
                if exit_code == 0 and not valid_nextest_evidence(nextest_evidence, run_id):
                    print("qualify-local: current-run nextest evidence is missing or inconsistent",
                          file=sys.stderr, flush=True)
                    exit_code = 2
                if exit_code == 0:
                    try:
                        nextest_raw = self.archive_nextest(receipt_dir, nextest_evidence)
                    except (EvidencePathError, OSError, QualificationError) as error:
                        print("qualify-local: cannot archive Nextest raw evidence: %s" % error,
                              file=sys.stderr, flush=True)
                        exit_code = 2
            advisory_db = None
            if (self.checkout / "tools/ci/advisory_db.py").is_file() and exit_code == 0:
                try:
                    current_advisory_db = json.loads(command(
                        ("python3", "-I", "-S", "tools/ci/python_gate.py", "tools/ci/advisory_db.py", "--json"), self.checkout,
                        env={**os.environ, "CARGO_HOME": str(self.checkout / "target/ci/cargo-home")},
                    ))
                except (ValueError, QualificationError) as error:
                    print("qualify-local: advisory DB evidence failed: %s" % error,
                          file=sys.stderr, flush=True)
                    exit_code = 2
                else:
                    deny_evidence = None
                    deny_raw = None
                    try:
                        deny_evidence, deny_raw = self.read_ci_evidence("deny-evidence.json")
                    except (OSError, ValueError, QualificationError) as error:
                        print("qualify-local: cannot read deny evidence: %s" % error,
                              file=sys.stderr, flush=True)
                    if not valid_deny_evidence(deny_evidence, run_id, current_advisory_db):
                        print("qualify-local: current-run deny evidence is missing or inconsistent",
                              file=sys.stderr, flush=True)
                        exit_code = 2
                    else:
                        advisory_db = dict(current_advisory_db)
                        advisory_db["qualification_run_id"] = run_id
                        advisory_db["gate_exit"] = 0
                        advisory_db["evidence_sha256"] = hashlib.sha256(deny_raw).hexdigest()
            durations = {}
            try:
                durations = recipe_durations(log_path)
                if exit_code == 0:
                    validate_recipe_durations(durations, expected_recipe_names(self.checkout))
            except (OSError, QualificationError) as error:
                print("qualify-local: recipe timing evidence failed: %s" % error,
                      file=sys.stderr, flush=True)
                exit_code = 2
            write_json_atomic(receipt_dir / "receipt.json", {
                "sha": sha, "tree": tree, "cmds": ["just ci"],
                "exit": exit_code, "duration_s": duration_s,
                "schema": 3,
                "status": "complete",
                "dirty": post_run_dirty,
                "tool_versions": observed_tools,
                "source_hashes": hashes,
                "recipe_duration_s": durations,
                "ci_log_sha256": hash_file(log_path),
                "qualification_run_id": run_id,
                "nextest": nextest_evidence,
                "nextest_raw": nextest_raw,
                "advisory_db": advisory_db,
            }, owned_root=self.root)
            print("qualify-local: receipt written to %s (exit=%d, duration_s=%d)" % (
                receipt_dir / "receipt.json", exit_code, duration_s
            ), flush=True)
            return exit_code


def main() -> int:
    driver = QualificationDriver(Path(__file__).resolve().parents[2])
    try:
        return driver.run()
    except (QualificationError, OSError) as error:
        print("qualify-local: " + str(error), file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
